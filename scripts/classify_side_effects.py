"""One-off migration (2026-10-14, gap G6): write an explicit `side_effects` into tools/*.json.

Every value below comes from reading the handler (lga_worker/tools/*.py and the provider methods they call, or the
Rust native tool) — the evidence column is what was found. Run with --check to verify the files already match;
without flags it inserts the missing `"side_effects"` property textually (no re-formatting of the contract files).

Values: none (reads only), possible (may write an artifact/cache file or touch the clipboard, never user data),
process (starts a program), yes (changes application, document, file or browser state).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# name -> (value, evidence)
CLASSES: dict[str, tuple[str, str]] = {}


def add(value: str, evidence: str, *names: str) -> None:
    for name in names:
        CLASSES[name] = (value, evidence)


add("none", "COM/provider getters only (probe, list_documents, get_entities, verify_geometry); no write/save/erase call in the handler or provider",
    "autocad.status", "autocad.list_documents", "autocad.get_entities", "autocad.verify_geometry")
add("none", "reads CDP state (attach, tabs, page_info, page_text, downloads list); no input, navigation or write call",
    "browser.status", "browser.tabs", "browser.get_state", "browser.page_matches", "browser.downloads")
add("none", "polls (sleep + match/list_windows) until a condition holds; performs no action on the page or window",
    "browser.wait_for", "desktop.wait_for_window")
add("none", "UI Automation reads (list_windows, get_ui_tree, find_element, read_element, window_texts); no invoke/click/set",
    "desktop.list_windows", "desktop.inspect_ui", "desktop.find_element", "desktop.read_element", "desktop.read_window_text")
add("none", "native Rust read_file / list_directory / stat / environment: metadata and content reads only",
    "filesystem.read", "filesystem.list", "filesystem.stat", "system.environment")
add("none", "reports backend status only", "vision.status")
add("possible", "reads the screen or page and saves the capture as a PNG under artifacts/ (desktop: take_screenshot mkdir+save; browser: provider.screenshot -> artifact_dir); no user data touched",
    "desktop.screenshot", "browser.screenshot", "desktop.observe", "paint.inspect")
add("possible", "reads pixels / calls the vision backend and stores crops or captures under artifacts/",
    "vision.ocr", "vision.describe")
add("possible", "fetches a reference picture and caches it under artifacts/ (ReferenceRecord store); no application state",
    "art.brief")
add("process", "starts a program (COM launch / process spawn)", "autocad.launch", "desktop.launch_app")
add("yes", "creates, modifies, exports or saves drawing content (provider.create_*/erase/save/export_*/zoom_extents/draw_strokes)",
    "autocad.new_document", "autocad.create_line", "autocad.create_circle", "autocad.create_polyline", "autocad.create_text",
    "autocad.create_layer", "autocad.save", "autocad.export_dxf", "autocad.export_pdf", "autocad.zoom_extents", "autocad.erase",
    "autocad.draw_image")
add("yes", "drives a page: navigation, tabs, clicks, typing, keys, scroll, upload (provider.navigate/switch_tab/close_tab/click/send_keys/scroll/upload/go_back)",
    "browser.open", "browser.navigate", "browser.switch_tab", "browser.close_tab", "browser.click", "browser.type",
    "browser.press_keys", "browser.scroll", "browser.upload", "browser.go_back")
add("yes", "operates an application with real input or window management (click, type, keys, drag, scroll, set_value, move_mouse, focus, close, save_as)",
    "desktop.close_app", "desktop.focus_window", "desktop.set_value", "desktop.click", "desktop.move_mouse", "desktop.drag",
    "desktop.scroll", "desktop.type", "desktop.press_key", "desktop.hotkey", "desktop.save_as")
add("yes", "draws in the target application and saves/compares captures (paint/art engines drive the real UI or COM)",
    "art.draw", "art.paint", "paint.draw", "paint.draw_image")
add("yes", "native Rust write_file: creates or overwrites a file", "filesystem.write")


def load_contract() -> dict[str, tuple[Path, dict]]:
    out = {}
    for f in sorted((ROOT / "tools").glob("*.json")):
        for tool in json.loads(f.read_text(encoding="utf-8"))["tools"]:
            out[tool["name"]] = (f, tool)
    return out


def report() -> str:
    contract = load_contract()
    flips = [n for n, (v, _) in CLASSES.items()
             if contract[n][1]["verification"] != "none" and v in ("none", "possible")]
    lines = [
        "# Tool contract report (generated by scripts/classify_side_effects.py --report)",
        "",
        f"{len(contract)} tools. `side_effects`: none = reads only; possible = may write an artifact/cache or touch the clipboard;",
        "process = starts a program; yes = changes application, document, file or browser state.",
        "",
        "## Behaviour-relevant reclassifications (the only ones)",
        "",
        "`changes_state()` (core/rust-agent/src/tools.rs) is true unless side_effects is none/possible (or, when absent,",
        "verification is none). It is used for (a) the 'results not seen yet' deferral of task.complete inside a reply and",
        "(b) the list of unconfirmed state changes that need completion checks (self-verified steps are excluded already).",
        "These tools were derived as state-changing only because their verification mode is self; the handlers are read-only:",
        "",
    ] + [f"* `{n}`: {CLASSES[n][0]}: {CLASSES[n][1]}" for n in flips] + [
        "",
        "Effect: a task.complete in the same reply as one of these now waits for the planner to see the result.",
        "Everything else keeps its previous effective value.",
        "",
        "## All tools",
        "",
        "| tool | side_effects | verification | risk | idempotent | source |",
        "|---|---|---|---|---|---|",
    ]
    for name in sorted(contract):
        t = contract[name][1]
        src = "evidence below" if name in CLASSES else "declared before"
        lines.append(f"| {name} | {t['side_effects']} | {t['verification']} | {t['risk_level']} | {'yes' if t['idempotent'] else 'no'} | {src} |")
    lines += ["", "## Evidence for the 68 classified in this migration", ""]
    for name in sorted(CLASSES):
        lines.append(f"* `{name}` = {CLASSES[name][0]}: {CLASSES[name][1]}")
    return chr(10).join(lines) + chr(10)


def main() -> int:
    if "--report" in sys.argv:
        out = ROOT / "docs" / "architecture" / "tool-contract-report.md"
        out.write_bytes(report().encode("utf-8"))
        print("wrote", out)
        return 0
    contract = load_contract()
    missing = [n for n, (_, t) in contract.items() if t.get("side_effects") is None]
    unknown = [n for n in missing if n not in CLASSES]
    stale = [n for n in CLASSES if n not in contract]
    declared_conflict = [n for n, (_, t) in contract.items() if t.get("side_effects") is not None and n in CLASSES
                         and t["side_effects"] != CLASSES[n][0]]
    if "--check" in sys.argv:
        problems = []
        if missing:
            problems.append(f"{len(missing)} tools without side_effects: {missing[:5]}...")
        if stale:
            problems.append(f"classes for unknown tools: {stale}")
        if declared_conflict:
            problems.append(f"contract disagrees with the evidence table: {declared_conflict}")
        print("OK" if not problems else "\n".join(problems))
        return 1 if problems else 0
    if unknown or stale:
        print("no evidence recorded for:", unknown, "| stale:", stale)
        return 2
    by_file: dict[Path, list[str]] = {}
    for n in missing:
        by_file.setdefault(contract[n][0], []).append(n)
    for path, names in by_file.items():
        text = path.read_text(encoding="utf-8")
        for name in names:
            value = CLASSES[name][0]
            start = text.index(f'"name": "{name}"')
            m = re.compile(r'"policy_category":\s*"[^"]*"').search(text, start)
            assert m, name
            text = text[: m.end()] + f', "side_effects": "{value}"' + text[m.end():]
        path.write_bytes(text.encode("utf-8"))
        json.loads(text)  # still valid JSON
    print(f"wrote side_effects for {len(missing)} tools in {len(by_file)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
