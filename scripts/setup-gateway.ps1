# Prepare both Gemini Web backends under runtime/gateway/ (git-ignored). Idempotent.
#
#   pwsh scripts/setup-gateway.ps1            # build/configure primary + fallback
#   pwsh scripts/setup-gateway.ps1 -SkipFallback
#
# What it does:
#   1. Generates local API keys (gateway, primary API, primary admin) into .env if they are missing.
#      These protect the localhost services; they are NOT Google credentials.
#   2. Builds gemini-web2api-go from references/ (pinned commit) with Go >= 1.26 and writes its
#      config.json bound to 127.0.0.1.
#   3. Creates a Python 3.12 venv for WebAI-to-API, installs its pinned requirements, and writes a
#      config.conf with host-browser cookie scraping disabled ([Browser] name = none).
#   4. Syncs the gateway's own venv.
# It never reads browser cookies. Google sign-in for the backends is a separate, user-driven step
# (see docs/operations.md "Connecting Gemini accounts").

param([switch]$SkipFallback, [switch]$SkipPrimary)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'env.ps1')
$root = $env:LGA_ROOT
$runtime = Join-Path $root 'runtime\gateway'
New-Item -ItemType Directory -Force $runtime | Out-Null

function New-Secret {
    $bytes = [byte[]]::new(32)
    [System.Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
    return [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Ensure-DotEnvSecret([string]$name) {
    $envFile = Join-Path $root '.env'
    $lines = if (Test-Path $envFile) { @(Get-Content $envFile) } else { @() }
    if ($lines | Where-Object { $_ -match "^\s*$name\s*=" }) { return 'kept' }
    Add-Content -Path $envFile -Value "$name=$(New-Secret)" -Encoding utf8
    return 'generated'
}

foreach ($name in 'LGA_GATEWAY_API_KEY', 'LGA_PRIMARY_API_KEY', 'LGA_PRIMARY_ADMIN_TOKEN') {
    '{0,-26} {1}' -f $name, (Ensure-DotEnvSecret $name)
}

if (-not $SkipPrimary) {
    $go = Get-Command go -ErrorAction SilentlyContinue
    if (-not $go) { throw 'Go is not installed. Install Go >= 1.26 (docs/environment.md, section Go).' }
    $src = Join-Path $root 'references\gemini-web2api-go'
    if (-not (Test-Path (Join-Path $src 'go.mod'))) { throw "missing $src; run scripts/fetch-references.ps1" }
    $out = Join-Path $runtime 'gemini-web2api-go'
    New-Item -ItemType Directory -Force (Join-Path $out 'data') | Out-Null
    Push-Location $src
    try {
        $env:GOFLAGS = '-mod=readonly'
        & go build -trimpath -o (Join-Path $out 'gemini-web2api-go.exe') .
        if ($LASTEXITCODE -ne 0) { throw 'go build failed' }
    } finally { Pop-Location }
    $config = [ordered]@{
        host               = '127.0.0.1'
        port               = 8083
        db_path            = (Join-Path $out 'data\gemini.db')
        admin_enabled      = $true
        log_requests       = $false
        request_timeout_sec = 160
        anon_first         = $true
    }
    $config | ConvertTo-Json | Set-Content -Path (Join-Path $out 'config.json') -Encoding utf8
    "primary   built $(Join-Path $out 'gemini-web2api-go.exe')"
}

if (-not $SkipFallback) {
    $src = Join-Path $root 'references\webai-to-api'
    if (-not (Test-Path (Join-Path $src 'requirements.txt'))) { throw "missing $src; run scripts/fetch-references.ps1" }
    $work = Join-Path $runtime 'webai-to-api'
    $venv = Join-Path $work 'venv'
    New-Item -ItemType Directory -Force $work, (Join-Path $work 'runtime'), (Join-Path $work 'runtime\auth') | Out-Null
    if (-not (Test-Path (Join-Path $venv 'Scripts\python.exe'))) {
        & uv venv --python 3.12 $venv
        if ($LASTEXITCODE -ne 0) { throw 'uv venv failed' }
    }
    & uv pip install --python (Join-Path $venv 'Scripts\python.exe') -r (Join-Path $src 'requirements.txt')
    if ($LASTEXITCODE -ne 0) { throw 'installing WebAI-to-API requirements failed' }
    @'
# Generated by scripts/setup-gateway.ps1. No credentials in this file.
[General]
check_updates = false

[Browser]
# "none" disables WebAI-to-API's automatic host-browser cookie extraction (browser_cookie3 / DPAPI).
name = none
runtime = playwright

[Gemini]
backend = webapi
default_model = gemini-3-flash
extended_thinking = false

[EnabledAI]
gemini = true
'@ | Set-Content -Path (Join-Path $work 'config.conf') -Encoding utf8
    "fallback  venv $venv"
}

Push-Location (Join-Path $root 'services\gemini-gateway')
try {
    & uv sync
    if ($LASTEXITCODE -ne 0) { throw 'uv sync for services/gemini-gateway failed' }
} finally { Pop-Location }
'gateway   venv ready'
